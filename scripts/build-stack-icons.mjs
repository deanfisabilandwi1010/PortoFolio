// Generates src/data/stackIcons.ts from Simple Icons (CC0) so the app ships only the
// few path strings it needs instead of the whole icon package.
// Run: node scripts/build-stack-icons.mjs
import * as si from "simple-icons";
import { writeFile } from "node:fs/promises";

const map = {
  TypeScript: "siTypescript",
  React: "siReact",
  "Next.js": "siNextdotjs",
  "Tailwind CSS": "siTailwindcss",
  Zod: "siZod",
  GSAP: "siGsap",
  "Three.js": "siThreedotjs",
  Laravel: "siLaravel",
  PHP: "siPhp",
  Supabase: "siSupabase",
  PostgreSQL: "siPostgresql",
  Vite: "siVite",
  Vitest: "siVitest",
  "Git & GitHub": "siGithub",
  Vercel: "siVercel",
  Netlify: "siNetlify",
  SecurityScorecard: "siSecurityscorecard",
};
// An original padlock for TLS (a protocol, not a brand).
const PADLOCK =
  "M12 1a5 5 0 0 0-5 5v3H5.5A1.5 1.5 0 0 0 4 10.5v11A1.5 1.5 0 0 0 5.5 23h13a1.5 1.5 0 0 0 1.5-1.5v-11A1.5 1.5 0 0 0 18.5 9H17V6a5 5 0 0 0-5-5Zm-3 8V6a3 3 0 0 1 6 0v3H9Zm3 4a2 2 0 0 1 1 3.73V19h-2v-2.27A2 2 0 0 1 12 13Z";

const lines = Object.entries(map).map(([name, key]) => {
  if (!si[key]) throw new Error(`missing icon ${key}`);
  return `  ${JSON.stringify(name)}: ${JSON.stringify(si[key].path)},`;
});
lines.push(`  "TLS & headers": ${JSON.stringify(PADLOCK)},`);

await writeFile(
  "src/data/stackIcons.ts",
  `// Generated by scripts/build-stack-icons.mjs — monochrome brand marks from Simple Icons (CC0).
// Drawn in currentColor so they take the palette colour of their cell. Tools without a mark
// (Zustand, Lenis, Playwright) fall back to their symbol.
export const stackIcons: Record<string, string | undefined> = {
${lines.join("\n")}
};
`,
);
console.log(`wrote ${lines.length} icons`);
